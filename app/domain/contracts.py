"""Puertos síncronos sustituibles por adaptadores HTTP."""
from typing import Protocol, Any
from .models import TechnicalConfiguration, Laminate, Composition, Validation, Calculation

class ConfigurationPort(Protocol):
    def defaults(self) -> TechnicalConfiguration: ...
    def validate(self, data: Any) -> TechnicalConfiguration: ...
    def profile(self, config: TechnicalConfiguration) -> str: ...

class LaminatePort(Protocol):
    def create(self, configuration: TechnicalConfiguration) -> dict: ...
    def selected(self, data: Any) -> tuple[Laminate, ...]: ...
    def edit(self, rows: tuple[Laminate, ...], record_id: str, changes: dict) -> tuple[Laminate, ...]: ...
    def remove(self, rows: tuple[Laminate, ...], record_id: str) -> tuple[Laminate, ...]: ...

class CompositionPort(Protocol):
    def calculate(self, laminates: tuple[Laminate, ...], configuration: TechnicalConfiguration) -> Composition: ...

class ValidationPort(Protocol):
    def validate(self, composition: Composition | None, configuration: TechnicalConfiguration) -> Validation: ...

class ExportPort(Protocol):
    def export(self, calculation: Calculation) -> bytes: ...
